import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {evaluateRisks} from '../tests/helpers/skin-quality-risks.mjs';
import {inventory} from '../src/skins/workflow.mjs';
import {hash} from '../src/skins/package.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const relativeDirectory='work/skin-quality-risks/'+randomUUID(),directory=join(root,relativeDirectory);
const corpus=JSON.parse(await readFile(join(root,'tests/fixtures/skin-quality-risks.json'),'utf8'));
await mkdir(directory,{recursive:true});
const report=await evaluateRisks(directory,corpus);
const evidence=[];
for(const dir of ['src/skins','tools/panel-slicer/src'])for(const f of await inventory(join(root,dir)))evidence.push({...f,file:dir+'/'+f.file});
for(const file of ['tests/helpers/skin-quality-risks.mjs','scripts/skin-quality-risks.mjs','tests/fixtures/skin-quality-risks.json','package-lock.json'])evidence.push({file,sha256:hash(await readFile(join(root,file)))});
report.implementationSha256=hash(Buffer.from(JSON.stringify(evidence)));
await writeFile(join(directory,'implementation.json'),JSON.stringify(evidence,null,2));
await writeFile(join(directory,'report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({directory:relativeDirectory,counts:report.counts,visualReviewDecision:report.visualReviewDecision},null,2));
