import {canvasField,selectObject,dismissCanvasPanels,panCanvas,scenePixels} from './canvas-controls.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { prepareReferenceScreen } from '../helpers/reference-screen.mjs';
import { buildStudio, dependency } from '../../scripts/studio-build.mjs';
import { startStudio } from '../../src/studio/host.mjs';
import { loadSceneKit, readMap, exportScene, openSceneExport } from '../../src/index.mjs';
import { unpackStored } from '../helpers/archive.mjs';
import { hash } from '../../src/generation/common.mjs';

test('reference screen: layered framing, style-aware placement, curve edit and portable export survive responsive rendering', { timeout: 240000 }, async t => {
  const c = prepareReferenceScreen(t); c.buildScreen();
  const kit = loadSceneKit(join(c.screenOut, 'kit')), exported = join(c.parent, 'portable-screen'); exportScene(kit, readMap(kit), exported);
  const staticRoot = await buildStudio({ output: join(c.parent, 'static') }), host = await startStudio({ root: join(exported, 'kit'), staticRoot });
  t.after(() => host.close()); const { chromium } = dependency('playwright').require('playwright');
  const browser = await chromium.launch({ headless: true, ...(process.env.SCENE_KIT_BROWSER_CHANNEL ? { channel: process.env.SCENE_KIT_BROWSER_CHANNEL } : {}),
    args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--explicitly-allowed-ports='+new URL(host.url).port] }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 }), errors = [], external = [];
  page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.route('**/*', route => new URL(route.request().url()).origin === host.url ? route.continue() : (external.push(route.request().url()), route.abort()));
  await page.goto(host.url); await page.waitForSelector('body[data-ready="true"]', { timeout: 90000 });
  const state = () => page.evaluate(async () => (await fetch('/api/state')).json()), initial = await state();
  assert.equal(initial.modules.length, 1517); assert.equal(initial.scene.format, 'ai_scene_compiled_v5');
  await page.getByRole('button',{name:'画刷',exact:true}).click(); assert.equal(await page.locator('#palette button').count(), 1);assert.equal(await page.getByRole('button',{name:'地形画刷',exact:true}).count(),1); assert.match(await page.locator('#appearance-note').innerText(), /8 格/);
  assert.equal(await page.locator('vite-error-overlay,nextjs-portal').count(), 0);
  await page.getByRole('checkbox', { name: '网格', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Play Mode', exact: true }).click();
  const framed = hash(await scenePixels(page));
  await page.getByRole('checkbox', { name: '显示图层 foreground-canopy', exact: true }).uncheck();
  assert.notEqual(hash(await scenePixels(page)), framed);
  await page.getByRole('checkbox', { name: '显示图层 foreground-canopy', exact: true }).check();
  assert.equal(hash(await scenePixels(page)), framed);
  assert.deepEqual((await state()).history, initial.history);
  await page.getByRole('button', { name: '退出 Play Mode', exact: true }).click();
  await page.getByRole('button', { name: '素材', exact: true }).click();
  await page.getByRole('button', { name: '放置模块 reference.bottom-canopy-right', exact: true }).click();
  await (await canvasField(page,'cell-x')).fill('11'); await (await canvasField(page,'cell-y')).fill('7');
  await (await canvasField(page,'apply-cell')).click();
  await page.waitForFunction(() => document.body.dataset.revision === '1');
  const placed = await state(), added = placed.document.instances.find(item => item.instanceId.startsWith('user.'));
  assert.equal(added.layerId, 'foreground-canopy');
  assert.equal(placed.scene.layers.find(layer => layer.layerId === 'foreground-canopy').nodes.find(node => node.logicalAnchor.x === 704).renderStyle.tint, 0x254e58);
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await page.waitForFunction(() => document.body.dataset.revision === '2');
  await (await canvasField(page,'curve-y')).fill('432'); await page.getByRole('button', { name: '应用曲线参数', exact: true }).click();
  await page.waitForFunction(() => document.body.dataset.revision === '3'); assert.equal((await state()).document.curveTerrains[0].points[1].y, 432);
  await page.getByRole('button', { name: '撤销', exact: true }).click(); await page.waitForFunction(() => document.body.dataset.revision === '4');
  assert.deepEqual((await state()).scene, initial.scene);
  const pending = page.waitForEvent('download'); await page.locator('#download-menu>summary').click();await page.locator('#export-pack').click();
  const zip = readFileSync(await (await pending).path()), unpacked = join(c.parent, 'downloaded-screen'); unpackStored(zip, unpacked);
  assert.deepEqual(openSceneExport(unpacked).compiled, initial.scene);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('canvas').width === Math.round(document.getElementById('canvas-host').clientWidth));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
});
