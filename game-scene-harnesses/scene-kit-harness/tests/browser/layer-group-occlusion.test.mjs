import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,dirname,resolve} from 'node:path';
import {loadSceneKit,readMap} from '../../src/kit.mjs';
import {buildStudio,dependency,packageRoot} from '../../scripts/studio-build.mjs';
import {startStudio} from '../../src/studio/host.mjs';
import {inspectPng} from '../../src/png.mjs';
import {scenePixels} from './canvas-controls.mjs';

test('original groups remain, and explicitly aligning terrain above scenery changes actual occlusion without moving artwork',{timeout:90000},async t=>{
 const base=resolve(tmpdir()),temp=mkdtempSync(join(base,'scene-group-occlusion-'));let browser,host;
 t.after(async()=>{await browser?.close();await host?.close();assert.equal(dirname(temp),base);rmSync(temp,{recursive:true,force:true});});
 const root=join(packageRoot,'tests/fixtures/synthetic'),map=readMap(loadSceneKit(root));
 map.inspectionCases=[];map.terrainRuns=[{x:1,y:6,length:5,familyId:'terrain.primary'}];
 Object.assign(map.instances.find(i=>i.instanceId==='marker.main'),{x:100,y:405});
 map.layers.push({layerId:'platform',kind:'environment',zIndex:30,parallax:{x:1,y:1},visible:true});
 Object.assign(map.assemblyInstances[0],{layerId:'platform',column:10,row:6});
 const staticRoot=await buildStudio({output:join(temp,'static')});
 host=await startStudio({root,staticRoot,initialDocument:map,workspaceRoot:join(temp,'projects')});
 const {chromium}=dependency('playwright').require('playwright');
 browser=await chromium.launch({headless:true,channel:'msedge',args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--explicitly-allowed-ports='+new URL(host.url).port]});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],external=[];
 page.on('pageerror',e=>errors.push(e.message));await page.route('**/*',r=>new URL(r.request().url()).origin===host.url?r.continue():(external.push(r.request().url()),r.abort()));
 await page.goto(host.url+'/editor');await page.waitForSelector('body[data-ready="true"]');await page.locator('#grid').uncheck();
 const snap=()=>page.evaluate(async()=>(await fetch('/api/state')).json());
 const pixel=async()=>{
  const camera=await page.locator('#minimap rect').last().evaluate(r=>Object.fromEntries(['x','y','width','height'].map(k=>[k,+r.getAttribute(k)])));
  const image=inspectPng(await scenePixels(page),{includePixels:true});
  const x=Math.floor((120-camera.x)/camera.width*image.width),y=Math.floor((425-camera.y)/camera.height*image.height),p=(y*image.width+x)*4;
  return [...image.rgba.subarray(p,p+4)];
 };
 const before=await snap(),frontPixel=await pixel();
 const environmentEye=page.getByRole('checkbox',{name:'显示图层 environment',exact:true});
 await environmentEye.uncheck();const terrainPixel=await pixel();assert.notDeepEqual(frontPixel,terrainPixel);await environmentEye.check();
 const layerIds=['platform','terrain','environment','background'];
 const response=await page.request.post(host.url+'/api/edit',{headers:{Origin:host.url},data:{revision:before.revision,action:'commands',commands:[{type:'reorder-layers',layerIds}]}});
 assert.equal(response.status(),200);await page.reload();await page.waitForSelector('body[data-ready="true"]');await page.locator('#grid').uncheck();
 const aligned=await snap();assert.deepEqual(aligned.scene.layers.map(l=>l.layerId),layerIds.toReversed());
 assert.deepEqual({...aligned.document,layers:[]},{...before.document,layers:[]});
 const platform=page.locator('#layers>[data-layer-group="platform"]');
 assert.deepEqual(await platform.locator(':scope>[data-layer-group]').evaluateAll(rows=>rows.map(r=>r.dataset.layerGroup)),['terrain','environment']);
 assert.equal(await platform.locator('[data-layer-group="terrain"] [data-instance-id="pair.main"]').count(),1);
 assert.equal(await platform.locator('[data-layer-group="environment"] [data-instance-id="marker.main"]').count(),1);
 assert.deepEqual(await page.locator('#layers [data-source-layer]').evaluateAll(rows=>rows.map(r=>r.dataset.sourceLayer)),layerIds);
 assert.deepEqual(await pixel(),terrainPixel,'terrain really covers the scenery after author order alignment');
 await page.getByRole('button',{name:'撤销',exact:true}).click();await page.waitForFunction(n=>+document.body.dataset.revision>n,aligned.revision);
 assert.deepEqual((await snap()).document,before.document);assert.deepEqual(await pixel(),frontPixel);
 const undone=await snap();await page.getByRole('button',{name:'重做',exact:true}).click();await page.waitForFunction(n=>+document.body.dataset.revision>n,undone.revision);
 assert.deepEqual(await pixel(),terrainPixel);await page.reload();await page.waitForSelector('body[data-ready="true"]');
 assert.deepEqual((await snap()).document,aligned.document);assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
});
