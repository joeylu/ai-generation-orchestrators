import test from 'node:test';
import assert from 'node:assert/strict';
import * as panel from '../src/index.mjs';
import {readJson} from '../src/io.mjs';
import {loadWorkspaceCore} from '../src/component-adapter.mjs';
import {headingThemeTarget,sectionHeadingVisible} from '../src/section-headings.mjs';
import {themePlanningGuide} from '../src/theme-planning.mjs';
import {effectivePanelTitleStyle} from '../src/title-bar.mjs';
const old=await readJson(new URL('../examples/modern-all-components.catalog.json',import.meta.url));
const catalog=await readJson(new URL('../examples/modern-action-headings.catalog.json',import.meta.url));
const {fixtures}=await readJson(new URL('./fixtures/action-heading-real-v1.json',import.meta.url)),core=await loadWorkspaceCore();
const flatten=node=>[node,...(node.children??[]).flatMap(flatten)];
const headings=b=>flatten(b.componentBundle.document.root).filter(n=>/\.section\.[^.]+\.title$/.test(n.id)).map(n=>n.props.text);
for(const fixture of fixtures)test(`heading v3 ${fixture.id}: hides structural action headings and preserves explicit show`,async()=>{
  const before=await panel.createPanelBundle(fixture.spec,old,core),spec=structuredClone(before.spec);
  spec.theme=headingThemeTarget(spec,old,catalog,'auto');
  const after=await panel.createPanelBundle(spec,catalog,core);
  assert.equal(before.compilerVersion,'0.32.0');assert.equal(after.compilerVersion,'0.33.0');
  assert.deepEqual(headings(after),spec.sections.length===1?[]:spec.sections.filter(s=>!s.rows.every(r=>r.kind==='button')).map(s=>s.title));
  assert.deepEqual(after.spec.sections,before.spec.sections);assert.deepEqual(after.spec.layout,before.spec.layout);
  assert.deepEqual(after.actions,before.actions);assert.deepEqual(after.bindings,before.bindings);assert.deepEqual(after.state,before.state);
  assert.equal(effectivePanelTitleStyle(after).horizontalAlign,'center');
  assert.deepEqual(await panel.validatePanelBundle(after,core),after);assert.deepEqual(await panel.validatePanelBundle(before,core),before);
  assert.throws(()=>panel.compilePanel(spec,catalog,core,undefined,undefined,'0.32.0'),{code:'COMPILER_VERSION'});
  assert.throws(()=>panel.compilePanel(spec,catalog,core,undefined,undefined,'0.31.0'),{code:'COMPILER_VERSION'});
  const native=await panel.createUnityDocument(after,core);
  assert.deepEqual(native.nodes.filter(n=>/\.section\.[^.]+\.title$/.test(n.id)).map(n=>n.text),headings(after));
  spec.theme=headingThemeTarget(spec,catalog,catalog,'show');
  const shown=await panel.createPanelBundle(spec,catalog,core);assert.deepEqual(headings(shown),spec.sections.map(s=>s.title));
  assert(flatten(shown.componentBundle.document.root).find(n=>n.id===spec.id+'.panel').layout.height>=flatten(after.componentBundle.document.root).find(n=>n.id===spec.id+'.panel').layout.height);
});
test('v3 keeps Tabs headings and uses structure, not a list of forbidden names',()=>{
  const section={title:'音频',rows:[{kind:'button'}]},spec={title:'菜单',sections:[section,{title:'画面',rows:[{kind:'switch'}]}],tabs:null};
  assert.equal(sectionHeadingVisible(spec,section,'concise-v3'),false);
  assert.equal(sectionHeadingVisible({...spec,tabs:{}},section,'concise-v3'),true);
  assert.equal(sectionHeadingVisible(spec,section,'visible-v3'),true);
  assert.equal(sectionHeadingVisible(spec,section,'concise-v2'),true);
  assert.equal(sectionHeadingVisible(spec,{title:'暂停操作',rows:[{kind:'switch'}]},'concise-v3'),true);
  assert(themePlanningGuide(catalog).includes('button-only action sections'));
});
